/**
 * Regenerates src/data/brandLogos.ts from Simple Icons (https://simpleicons.org).
 * Re-run after adding a brand to src/data/brands.ts:
 *
 *   node scripts/fetch-brand-logos.mjs
 *
 * Simple Icons ship one 24x24 path per brand, which is exactly what
 * react-native-svg wants — so we inline the path data instead of bundling files.
 * The icons themselves are CC0; the marks stay the property of their owners.
 *
 * Not every brand has an icon (Mercedes-Benz, Alfa Romeo and Land Rover were
 * never added / have been removed upstream). Those are reported and simply
 * absent from the map — <BrandLogo> falls back to a monogram.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** brandId in src/data/brands.ts → Simple Icons slug, when the two differ. */
const SLUG_OVERRIDES = {
  'aston-martin': 'astonmartin',
  'alfa-romeo': 'alfaromeo',
  'land-rover': 'landrover',
};

function brandIds() {
  const source = readFileSync(join(root, 'src/data/brands.ts'), 'utf8');
  return [...source.matchAll(/^\s*(?:\{\s*)?id: '([^']+)'/gm)].map((match) => match[1]);
}

async function fetchIcon(slug) {
  const response = await fetch(`https://cdn.simpleicons.org/${slug}`);
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`${slug}: HTTP ${response.status}`);

  const svg = await response.text();
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);

  if (viewBox !== '0 0 24 24') throw new Error(`${slug}: unexpected viewBox ${viewBox}`);
  if (paths.length !== 1) throw new Error(`${slug}: expected 1 path, got ${paths.length}`);

  return paths[0];
}

const logos = [];
const missing = [];

for (const id of brandIds()) {
  const slug = SLUG_OVERRIDES[id] ?? id.replace(/-/g, '');
  const path = await fetchIcon(slug);

  if (path) logos.push({ id, slug, path });
  else missing.push({ id, slug });
}

const body = logos
  .map(({ id, slug, path }) => `  /** simpleicons.org/${slug} */\n  '${id}': '${path}',`)
  .join('\n');

const header = `/**
 * Brand marks as single 24x24 SVG paths, from Simple Icons (CC0).
 * GENERATED by scripts/fetch-brand-logos.mjs — do not edit by hand.
 *
 * Brands absent from Simple Icons fall back to a monogram in <BrandLogo>:
${missing.map(({ id }) => ` *   - ${id}`).join('\n') || ' *   (none)'}
 */

/** Every path is authored against this box, so <Svg viewBox> is constant. */
export const BRAND_LOGO_VIEW_BOX = '0 0 24 24';

export const BRAND_LOGO_PATHS: Record<string, string> = {
${body}
};

export function getBrandLogoPath(brandId: string): string | undefined {
  return BRAND_LOGO_PATHS[brandId];
}
`;

writeFileSync(join(root, 'src/data/brandLogos.ts'), header);

console.log(`Wrote src/data/brandLogos.ts — ${logos.length} logos.`);
if (missing.length) {
  console.log(`No Simple Icons entry for: ${missing.map(({ slug }) => slug).join(', ')}`);
}
